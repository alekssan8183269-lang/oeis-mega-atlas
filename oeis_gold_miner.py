import pandas as pd
import numpy as np

# НАСТРОЙКИ
INPUT_FILE = "oeis_mega_atlas_140fields.csv" # Имя вашего 40-колоночного файла
TOP_N = 5 # Сколько лучших рядов выводить в каждой номинации

def mine_gold():
    print("⚡ Запуск поисковой машины... Ищем золото в математическом мусоре...")
    
    try:
        # Читаем наш мега-атлас (Excel-безопасный UTF-8)
        df = pd.read_csv(INPUT_FILE, encoding="utf-8-sig")
    except FileNotFoundError:
        print(f"❌ ОШИБКА: Файл {INPUT_FILE} не найден в папке! Сначала запустите основной конвейер.")
        return

    # Очищаем данные от пропущенных строк (Status == Skip)
    df_clean = df[df["Status"] == "Успешно"].copy()
    
    if len(df_clean) == 0:
        print("⚠ В таблице нет успешно обработанных рядов для анализа!")
        return
        
    print(f"📊 Успешно загружено для поиска: {len(df_clean)} реальных последовательностей.")
    print("="*70)

    # -----------------------------------------------------------------
    # НОМИНАЦИЯ 1: "КОСМИЧЕСКИЕ СМЕРЧИ" (Максимальная сила ротора)
    # -----------------------------------------------------------------
    print("🌀 НОМИНАЦИЯ 1: 'КОСМИЧЕСКИЕ СМЕРЧИ' (Максимальная закрутка в 3D)")
    # Сортируем по силе ротора, исключая бесконечности
    smersh = df_clean.sort_values(by="Сила_Ротора_Закрутки", ascending=False).head(TOP_N)
    for idx, row in smersh.iterrows():
        print(f"  ⭐ {row['ID']} | Ротор: {row['Сила_Ротора_Закрутки']} | {row['Название'][:60]}...")
    print("-"*70)

    # -----------------------------------------------------------------
    # НОМИНАЦИЯ 2: "ТЕКТОНИЧЕСКИЕ СДВИГИ" (Самый убойный скачок аномалий)
    # -----------------------------------------------------------------
    print("🌋 НОМИНАЦИЯ 2: 'ТЕКТОНИЧЕСКИЕ СДВИГИ' (Ряды со скрытым сбоем/изломом)")
    shifts = df_clean.sort_values(by="Коэф_Аномалий_Шага", ascending=False).head(TOP_N)
    for idx, row in shifts.iterrows():
        print(f"  ⭐ {row['ID']} | Скачок в: {row['Коэф_Аномалий_Шага']} раз! | {row['Название'][:60]}...")
    print("-"*70)

    # -----------------------------------------------------------------
    # НОМИНАЦИЯ 3: "ИДЕАЛЬНЫЙ ПОРЯДОК БЕНФОРДА" (Природные матрицы)
    # -----------------------------------------------------------------
    print("📐 НОМИНАЦИЯ 3: 'МАТРИЦЫ ЖИВОЙ ПРИРОДЫ' (Идеальное подчинение закону Бенфорда)")
    # Ищем девиацию (отклонение) максимально близкую к 0, но исключаем уродливые дефолтные значения
    benford = df_clean[df_clean["Девиация_Закона_Бенфорда"] > 0].sort_values(by="Девиация_Закона_Бенфорда", ascending=True).head(TOP_N)
    for idx, row in benford.iterrows():
        print(f"  ⭐ {row['ID']} | Ошибка Бенфорда: {row['Девиация_Закона_Бенфорда']} | {row['Название'][:60]}...")
    print("-"*70)

    # -----------------------------------------------------------------
    # НОМИНАЦИЯ 4: "СВЕРХСЛОЖНЫЕ ГИПЕР-КОРАЛЛЫ" (Высшая фрактальная энтропия)
    # -----------------------------------------------------------------
    print("🪸 НОМИНАЦИЯ 4: 'ГИПЕР-КОРАЛЛЫ ВЫСШЕГО ПОРЯДКА' (Максимальная фрактальная мерность)")
    corals = df_clean.sort_values(by="Фрактал_Размерность_GP", ascending=False).head(TOP_N)
    for idx, row in corals.iterrows():
        print(f"  ⭐ {row['ID']} | Размерность: {row['Фрактал_Размерность_GP']} | Ентропия: {row['Энтропия_Шеннона']} | {row['Название'][:60]}...")
    print("-"*70)

    # -----------------------------------------------------------------
    # НОМИНАЦИЯ 5: Поиск "РЯДОВ-БЛИЗНЕЦОВ" (Скрытые мосты геометрии)
    # -----------------------------------------------------------------
    print("🤝 НОМИНАЦИЯ 5: 'СКРЫТЫЕ МОСТЫ ГЕОМЕТРИИ' (Абсолютно разные ряды с идентичным паспортом)")
    
    # Берем ключевые метрики для проверки близости
    features = ["Энтропия_Шеннона", "Херст_Хаотичность", "Сила_Ротора_Закрутки", "Коэф_Аномалий_Шага"]
    
    twins_found = 0
    checked_pairs = set()
    
    # Чтобы не зависнуть, ищем близнецов среди ТОП-200 по энтропии (безопасно для ОЗУ)
    subset = df_clean.sort_values(by="Энтропия_Шеннона").head(200).copy()
    
    for i in range(len(subset)):
        for j in range(i + 1, len(subset)):
            row1 = subset.iloc[i]
            row2 = subset.iloc[j]
            
            # Проверяем, что это РАЗНЫЕ последовательности
            if row1['ID'] == row2['ID']: continue
            
            # Считаем разницу паспортов по Фурье амплитудам (возьмем первые 5 амплитуд для примера)
            diff_amp = 0.0
            for k in range(1, 6):
                diff_amp += abs(row1[f"Фурье_Амплитуда_{k}"] - row2[f"Фурье_Амплитуда_{k}"])
                
            # Если амплитуды Фурье-спектра почти идентичны (мост найден!)
            if diff_amp < 5.0 and twins_found < TOP_N:
                pair = tuple(sorted([row1['ID'], row2['ID']]))
                if pair not in checked_pairs:
                    checked_pairs.add(pair)
                    twins_found += 1
                    print(f"  🔗 НАЙДЕН МОСТ! Пара: {row1['ID']} и {row2['ID']}")
                    print(f"     -> Паспорт 1: {row1['Название'][:50]}...")
                    print(f"     -> Паспорт 2: {row2['Название'][:50]}...")
                    print(f"     -> Ошибка спектра Фурье между ними: {round(diff_amp, 2)}")
                    
    if twins_found == 0:
        print("  Близнецы в текущем батче данных не обнаружены. Нужно больше рядов для сопоставления.")

    print("="*70)
    print("👑 ОПЕРАЦИЯ 'ВЗРЫВ МОЗГА' ЗАВЕРШЕНА. ЛУЧШИЕ АНОМАЛИИ ВЫВЕДЕНЫ НА ЭКРАН!")

if __name__ == "__main__":
    mine_gold()
