import os
import time
import math
import numpy as np
import pandas as pd

# =====================================================================
# НАСТРОЙКИБЕСКОНЕЧНОГО ПРОТОЧНОГО КОНВЕЙЕРА
# =====================================================================
# Задаем лимит этого запуска (например, 10 миллионов или 1 миллиард шагов)
# Поменяй LIMIT на 1000000000 для тотального прогона!
TOTAL_STEPS_LIMIT = 50000000  # 50 миллионов шагов в потоке ради бешеной скорости
PATTERN_MATCH_LEN = 5         # Длина отслеживаемого интересного повтора
OUTPUT_LOG_FILE = "ramsey_infinity_stream_log.csv"

def safe_num(val, ndigits=6):
    try: return f'="{round(float(val), ndigits)}"'
    except: return f'="{val}"'

# =====================================================================
# ЯДРО ГЕНЕРАЦИИ: НЕЛИНЕЙНЫЙ РЕКУРРЕНТНЫЙ ПОТОК (НЕ ОДНИ ЕДИНИЧКИ)
# =====================================================================
if __name__ == "__main__":
    print("="*75)
    print("🛸 HASE v1.0-STREAM: ЗАПУСК ПРОТОЧНОГО ЛОВЦА ПРИЗРАКОВ РАМСЕЯ")
    print("="*75)
    print(f"🎯 Запуск генерации {TOTAL_STEPS_LIMIT} чисел в проточном режиме (без ОЗУ)...")
    
    start_time = time.time()
    
    # Стартовый "тупой", но сложный начальный вектор из разных чисел
    # Ряд генерирует следующее число на основе смеси трех предыдущих с нелинейным сдвигом
    x1, x2, x3 = 0.123456, 0.789012, 0.345678
    
    # Буфер для отслеживания текущего скользящего окна (последние 5 чисел)
    current_window = []
    
    # Хэш-таблица для капкана повторов: запоминает, на каком шаге впервые встретился конкретный паттерн
    # Чтобы не взорвать ОЗУ, мы будем хэшировать паттерн знаков приращений (вверх/вниз) 5 чисел
    pattern_traps = {}
    
    snapshot_data = []
    detected_repeats = []
    
    # Метки шагов, на которых мы ЖЕСТКО сохраняем ровно по 1 числу (логарифмическая шкала)
    log_milestones = set([1, 10, 100, 1000, 10000, 100000, 1000000, 5000000, 10000000, 50000000])
    
    # Каждые 5 миллионов шагов тоже будем кидать по 1 числу в таблицу
    checkpoint_interval = 1000000
    
    for step in range(1, TOTAL_STEPS_LIMIT + 1):
        # 1. Формула нелинейного генератора хаоса (смесь дробных хвостов и синуса)
        # Число всегда зажато строго в диапазоне от 0.0 до 1.0, но крутится по безумной орбите
        next_x = (math.abs(math.sin(x1 * 3.14159) * 4.321) + x2 * 0.111 + x3 * 0.777) % 1.0
        
        # Сдвигаем регистры времени (старые числа забываются процессором!)
        x1, x2, x3 = x2, x3, next_x
        
        # 2. КАПКАН ПОВТОРОВ: Наполняем скользящее окно знаков приращений
        if step > 1:
            sign_step = 1 if next_x > x3 else -1 if next_x < x3 else 0
            current_window.append(sign_step)
            if len(current_window) > PATTERN_MATCH_LEN:
                current_window.pop(0)
                
            # Если окно заполнено (ровно 5 знаков), проверяем его ДНК в нашей базе
            if len(current_window) == PATTERN_MATCH_LEN:
                pattern_key = tuple(current_window)
                if pattern_key in pattern_traps:
                    # ПРИЗРАК РАМСЕЯ ОБНАРУЖЕН! Паттерн в точности повторился!
                    first_seen_step = pattern_traps[pattern_key]
                    distance = step - first_seen_step
                    # Записываем только редкие, далекие повторы (например, если между ними больше 100 000 шагов)
                    if distance > 500000 and len(detected_repeats) < 50:
                        detected_repeats.append({
                            "Тип_События": "РАМСЕЙ_ПОВТОР_5_ЗНАКОВ",
                            "Шаг_Обнаружения": step,
                            "Впервые_Был_На_Шаге": first_seen_step,
                            "Дистанция_Сбоя_Матрицы": distance,
                            "Текущее_Значение": round(next_x, 6)
                        })
                        print(f"🚨 [СБОЙ МАТРИЦЫ] Паттерн {pattern_key} повторился через {distance} шагов! Шаг: {step}")
                else:
                    # Запоминаем узор, если ОЗУ не переполнена
                    if len(pattern_traps) < 2000000:
                        pattern_traps[pattern_key] = step

        # 3. ТОЧЕЧНЫЙ ДАТЧИК: Сохраняем ровно 1 число на критических вехах эволюции
        if step in log_milestones or step % checkpoint_interval == 0:
            snapshot_data.append({
                "Тип_События": f"ТОЧКА_ШАГА_{step}",
                "Шаг_Обнаружения": step,
                "Впервые_Был_На_Шаге": step,
                "Дистанция_Сбоя_Матрицы": 0,
                "Текущее_Значение": round(next_x, 6)
            })
            print(f"💾 [ДАТЧИК ФИКСАЦИИ] Шаг {step} -> Значение: {round(next_x, 6)}")

    # =====================================================================
    # СБОРКА РЕЗУЛЬТАТОВ В CSV ТАБЛИЦУ
    # =====================================================================
    # Объединяем точечные замеры и пойманные повторы Рамсея
    final_rows = snapshot_data + detected_repeats
    df_log = pd.DataFrame(final_rows)
    
    # Форматируем колонки под safe_num
    df_log["Шаг_Обнаружения"] = df_log["Шаг_Обнаружения"].apply(lambda x: safe_num(x, 0))
    df_log["Впервые_Был_На_Шаге"] = df_log["Впервые_Был_На_Шаге"].apply(lambda x: safe_num(x, 0))
    df_log["Дистанция_Сбоя_Матрицы"] = df_log["Дистанция_Сбоя_Матрицы"].apply(lambda x: safe_num(x, 0))
    df_log["Текущее_Значение"] = df_log["Текущее_Значение"].apply(lambda x: safe_num(x, 6))
    
    df_log.to_csv(OUTPUT_LOG_FILE, index=False, sep=";")
    
    print("\n" + "="*75)
    print("👑 ПРОТОЧНЫЙ ЭКСПЕРИМЕНТ ЗАВЕРШЕН БЕЗ ПЕРЕГРЕВА И ЗАСОРЕНИЯ ДИСКА!")
    print(f"📊 В лог-таблицу отложено {len(df_log)} критических точек и Рамсей-сбоев.")
    print(f"📂 Результаты лога ищи тут: {OUTPUT_LOG_FILE}")
    print(f"⏱️ Время прогона {TOTAL_STEPS_LIMIT} чисел: {round(time.time() - start_time, 2)} сек.")
    print("="*75)
